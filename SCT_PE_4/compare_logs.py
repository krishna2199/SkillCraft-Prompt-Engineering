"""Compare conversation logs across assistant versions with the same metrics.

Usage:  python SCT_PE_4/compare_logs.py > SCT_PE_4/report/consistency_metrics.md

Metrics are recomputed from each log's transcript, so older logs (v2.0) are measured the
same way as newer ones. Definitions:
  scored answers     - Ace turns with an "N/5" score, out of the scripted answers given
  multi-question     - Ace turns containing more than one "?"
  "the candidate"    - Ace turns that talk about the user in the third person
  placeholders       - Ace turns containing bracket placeholders such as [Your Name]
  finished           - the conversation reached the closing summary
"""

import json
import sys
from pathlib import Path

TASK_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(TASK_DIR))
from run_assistant import consistency_metrics  # noqa: E402

VERSIONS = ["v1_single_prompt", "v2.0_chained", "v2.1_chained"]


def main():
    print("# Task 4: Consistency metrics by version\n")
    print("Generated by `compare_logs.py` from the saved conversation logs in `results/`.\n")
    print("| Version | Conversation | Scored answers | Multi-question turns | Turns saying \"the candidate\" "
          "| Placeholder turns | Longest turn (words) | Finished |")
    print("|---|---|---|---|---|---|---|---|")
    for version in VERSIONS:
        for path in sorted((TASK_DIR / "results" / version).glob("*.json")):
            log = json.loads(path.read_text(encoding="utf-8"))
            m = consistency_metrics(log["transcript"], log["metrics"]["scripted_answers_given"])
            finished = log["final_state"].get("stage") == "done" or "average" in log["transcript"][-1]["text"].lower()
            link = f"[{path.stem}](../results/{version}/{path.stem}.md)"
            print(f"| {version} | {link} | {m['turns_with_numeric_score']}/{m['scripted_answers_given']} "
                  f"| {m['turns_with_more_than_one_question']} | {m['turns_calling_user_the_candidate']} "
                  f"| {m['turns_with_bracket_placeholders']} | {m['max_assistant_turn_words']} "
                  f"| {'yes' if finished else 'no'} |")


if __name__ == "__main__":
    main()
