"""Compute objective metrics for the Task 2 creative outputs.

Usage:  python SCT_PE_2/analyze_outputs.py > SCT_PE_2/report/automatic_metrics.md

Metrics per output:
  words            - length of the response (header excluded)
  fields           - required fields found / required (v3 headings, v4 pitch-card fields)
  name             - the startup name the model chose
  numeric claims   - sentences containing percentages, "billion/million", or CAGR (possible
                     unsupported statistics; each one is reviewed by hand in the report)
  example overlap  - share of the output's word 4-grams that also appear in the v4
                     few-shot examples (measures copying, not quality)
"""

import re
from pathlib import Path

TASK_DIR = Path(__file__).resolve().parent
RESULTS = TASK_DIR / "results"
V3_FIELDS = ["Startup Name", "Problem", "Target Users", "Proposed Solution", "Key Features",
             "Revenue Model", "Why It Is Different"]
V4_FIELDS = ["Name", "Hook", "Problem", "Who it's for", "How it works", "Three features",
             "Money", "Why it's different"]
# Keywords are case-insensitive; the captured name must start with a capital letter.
NAME_RES = [re.compile(p, re.M) for p in (
    r"^\W*(?i:startup name|product name|name)\W*:[ \t*\"]*([A-Z][\w-]+)",
    r"(?i:startup idea|idea):[ \t*\"]*([A-Z][\w-]+)",
    r"(?i:let's call it) \"?([A-Z][\w-]+)",
)]
NUMERIC_CLAIM = re.compile(r"[^.\n]*(\d+(?:\.\d+)?\s*%|\bCAGR\b|\b\d[\d,.]*\s*(?:billion|million)\b|one-third)[^.\n]*", re.I)


def body(path):
    return path.read_text(encoding="utf-8").split("\n---\n", 1)[1].strip()


def ngrams(text, n=4):
    tokens = re.findall(r"[a-z']+", text.lower())
    return {tuple(tokens[i:i + n]) for i in range(len(tokens) - n + 1)}


def few_shot_examples():
    prompt = (TASK_DIR / "prompts" / "prompt_v4.txt").read_text(encoding="utf-8")
    return prompt.split("Example 1", 1)[1].split("Now write ONE", 1)[0]


def field_coverage(text, fields):
    return sum(bool(re.search(r"^\W*" + re.escape(f) + r"\W*:", text, re.I | re.M)) or
               bool(re.search(r"^#+\s*" + re.escape(f), text, re.I | re.M)) for f in fields)


def main():
    example_grams = ngrams(few_shot_examples())
    rows, names = [], {}
    for path in sorted(RESULTS.glob("prompt_v*_seed*.md")):
        text = body(path)
        variant = path.stem.split("_seed")[0]
        name = next((m.group(1) for r in NAME_RES if (m := r.search(text))), "?")
        names.setdefault(variant, []).append(name)
        grams = ngrams(text)
        overlap = len(grams & example_grams) / max(1, len(grams))
        fields = {"prompt_v3": V3_FIELDS, "prompt_v4": V4_FIELDS}.get(variant)
        coverage = f"{field_coverage(text, fields)}/{len(fields)}" if fields else "n/a"
        claims = [m.group(0).strip() for m in NUMERIC_CLAIM.finditer(text)]
        rows.append((path.name, len(text.split()), coverage, name, len(claims),
                     f"{overlap:.1%}", claims))

    print("# Task 2: Automatic metrics\n")
    print("Generated by `analyze_outputs.py` from the saved outputs in `results/`. "
          "These counts support, but do not replace, the rubric scores in "
          "[comparison_report.md](comparison_report.md).\n")
    print("| Output | Words | Required fields | Startup name | Numeric claims | 4-gram overlap with few-shot examples |")
    print("|---|---|---|---|---|---|")
    for r in rows:
        print(f"| [{r[0]}](../results/{r[0]}) | {r[1]} | {r[2]} | {r[3]} | {r[4]} | {r[5]} |")
    print("\n## Name diversity across seeds\n")
    print("| Variant | Names (seeds 1, 2, 3) | Distinct |\n|---|---|---|")
    for variant, ns in names.items():
        print(f"| {variant} | {', '.join(ns)} | {len(set(ns))}/3 |")
    all_names = [n for ns in names.values() for n in ns]
    repeats = sorted({n for n in all_names if all_names.count(n) > 1})
    print(f"\nNames used more than once across all 12 outputs: {', '.join(repeats) or 'none'}.\n")
    print("## Numeric claims found (for manual fact-check)\n")
    for r in rows:
        for claim in r[6]:
            print(f"- `{r[0]}`: \"{claim}\"")


if __name__ == "__main__":
    main()
